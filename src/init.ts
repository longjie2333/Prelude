/**
 * `/prelude-init`, project part (plan M1-2, design §8): `.prelude/` with `project.json` (random
 * id), `.prelude/.gitignore` from the user's choice about versioning notes and reports, and a
 * marked Prelude section in `AGENTS.md` that re-running replaces in place; `runGlobalInit` is
 * the global part (M2-1).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import type { ExtensionContext } from "@earendil-works/pi-coding-agent";
import type { Prelude } from "./context.ts";
import { readConfig } from "./kb/config.ts";
import { setupKb } from "./kb/sync.ts";
import type { ProjectPaths } from "./paths.ts";
import { nowIso, randomHex, readJson, writeJson } from "./util.ts";

export interface ProjectInfo {
	id: string;
	createdAt: string;
	/** Whether notes/ and reports/ are versioned with the project. */
	track: { notes: boolean; reports: boolean };
}

export const AGENTS_BEGIN = "<!-- prelude:begin -->";
export const AGENTS_END = "<!-- prelude:end -->";

export const AGENTS_SECTION = `${AGENTS_BEGIN}
## Prelude

本项目由 Prelude 测试。被测系统的特点记在 \`.prelude/notes/\`，每个主题一个 Markdown 文件（例如 \`architecture.md\`、\`environments.md\`、\`known-issues.md\`）。

- 测试开始时先读这些笔记；测试中发现新事实（接口、角色与权限、数据流、技术栈、环境差异、已知问题和坑），就更新对应笔记。
- 笔记写这个系统本身。跨项目通用的经验不写在这里，复盘时通过 Prelude 的知识库工具提交。
- \`.prelude/scope.json\` 是授权范围：测试开始时模型会列出需要的授权请你确认，确认的内容由 Prelude 写入。不要让模型直接改这个文件。
${AGENTS_END}`;

export function readProject(p: ProjectPaths): ProjectInfo | undefined {
	return readJson<ProjectInfo>(p.projectFile);
}

export function gitignoreContent(track: ProjectInfo["track"]): string {
	const lines = ["# Generated by /prelude-init (design §8)", "work/", "evidence/", "runs/", "audit.jsonl"];
	if (!track.notes) lines.push("notes/");
	if (!track.reports) lines.push("reports/");
	return `${lines.join("\n")}\n`;
}

/** Inserts or replaces the marked section; everything outside the markers is kept as is. */
export function upsertAgentsSection(existing: string | undefined): string {
	if (existing === undefined || existing.trim() === "") return `${AGENTS_SECTION}\n`;
	const start = existing.indexOf(AGENTS_BEGIN);
	const end = existing.indexOf(AGENTS_END);
	if (start >= 0 && end > start) {
		return existing.slice(0, start) + AGENTS_SECTION + existing.slice(end + AGENTS_END.length);
	}
	return `${existing.replace(/\s*$/, "")}\n\n${AGENTS_SECTION}\n`;
}

export function initProject(p: ProjectPaths, track: ProjectInfo["track"]): ProjectInfo {
	for (const d of [p.dir, p.notesDir, p.reportsDir, p.workDir]) mkdirSync(d, { recursive: true });
	const previous = readProject(p);
	const info: ProjectInfo = {
		id: previous?.id ?? `p-${randomHex(4)}`,
		createdAt: previous?.createdAt ?? nowIso(),
		track,
	};
	writeJson(p.projectFile, info);
	writeFileSync(p.gitignore, gitignoreContent(track));
	const agents = existsSync(p.agentsFile) ? readFileSync(p.agentsFile, "utf8") : undefined;
	writeFileSync(p.agentsFile, upsertAgentsSection(agents));
	return info;
}

const TRACK_CHOICES: Array<[string, ProjectInfo["track"]]> = [
	["Notes and reports", { notes: true, reports: true }],
	["Notes only", { notes: true, reports: false }],
	["Reports only", { notes: false, reports: true }],
	["Neither", { notes: false, reports: false }],
];

/** Asks which of notes/ and reports/ to version; without a UI keeps the previous choice or versions neither. */
export async function askTrack(ctx: ExtensionContext, previous?: ProjectInfo["track"]): Promise<ProjectInfo["track"]> {
	const fallback = previous ?? { notes: false, reports: false };
	if (!ctx.hasUI) return fallback;
	const choice = await ctx.ui.select(
		"Version .prelude/notes and .prelude/reports with this project?",
		TRACK_CHOICES.map(([label]) => label),
	);
	return TRACK_CHOICES.find(([label]) => label === choice)?.[1] ?? fallback;
}

export async function runInit(ctx: ExtensionContext, p: ProjectPaths): Promise<ProjectInfo> {
	const track = await askTrack(ctx, readProject(p)?.track);
	const info = initProject(p, track);
	ctx.ui.notify(
		`Prelude initialized: project ${info.id}${existsSync(p.scopeFile) ? "" : ". The test will ask you for the authorization it needs"}`,
		"info",
	);
	return info;
}

/**
 * Global part (plan M2-1): `~/.prelude/config.json` and the knowledge base. Asks once for a git
 * remote; an empty answer, or no UI, gives a local-only knowledge base.
 */
export async function runGlobalInit(ctx: ExtensionContext, prelude: Prelude): Promise<void> {
	const previous = readConfig(prelude.preludeHome)?.kb;
	const remote = previous
		? previous.remote
		: ctx.hasUI
			? (
					await ctx.ui.input(
						"Git remote for the shared Prelude knowledge base (empty: local only)",
						"git@host:team/prelude-kb.git",
					)
				)?.trim() || undefined
			: undefined;
	const kb = await setupKb(
		{ home: prelude.preludeHome, remote, mainBranch: previous?.mainBranch, branch: previous?.branch },
		(e) => prelude.audit(e),
	);
	prelude.setKb(kb);
	ctx.ui.notify(
		`Knowledge base ready at ${kb.dir} (${kb.config.remote ? `branch ${kb.config.branch}, ${kb.state}` : "local only"})`,
		"info",
	);
}
